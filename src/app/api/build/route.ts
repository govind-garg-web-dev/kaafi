import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";
import JSZip from "jszip";

const EAS_JSON = {
  cli: { version: ">= 12.0.0" },
  build: {
    preview: {
      android: { buildType: "apk" },
      ios: { simulator: true },
    },
    production: {
      android: { buildType: "aab" },
      ios: {},
    },
  },
  submit: {
    production: {},
  },
};

export async function POST(req: NextRequest) {
  try {
    const supabase = await createClient();
    const { data: { user } } = await supabase.auth.getUser();
    if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

    // Studio plan required
    const { data: profile } = await supabase
      .from("profiles")
      .select("plan")
      .eq("id", user.id)
      .single();

    if (!profile || profile.plan !== "studio") {
      return NextResponse.json(
        { error: "Cloud builds are a Studio feature. Upgrade to Studio to use this." },
        { status: 403 }
      );
    }

    const { projectId, platform = "android" } = await req.json();
    if (!projectId) return NextResponse.json({ error: "projectId required." }, { status: 400 });

    // Fetch project + files
    const { data: project } = await supabase
      .from("projects")
      .select("name, prompt")
      .eq("id", projectId)
      .eq("user_id", user.id)
      .single();

    if (!project) return NextResponse.json({ error: "Project not found." }, { status: 404 });

    const { data: files } = await supabase
      .from("project_files")
      .select("path, content")
      .eq("project_id", projectId);

    // Create build record
    const { data: build } = await supabase
      .from("builds")
      .insert({
        project_id: projectId,
        user_id: user.id,
        platform,
        status: "queued",
      })
      .select()
      .single();

    // Build a ZIP that's EAS-ready
    const zip = new JSZip();
    const slug = project.name.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, "");
    const folder = zip.folder(slug) ?? zip;

    // Add generated project files
    for (const file of files ?? []) {
      folder.file(file.path, file.content);
    }

    // Add eas.json
    folder.file("eas.json", JSON.stringify(EAS_JSON, null, 2));

    // Update app.json with EAS fields if present
    const appJsonFile = (files ?? []).find((f) => f.path === "app.json");
    if (appJsonFile) {
      try {
        const appJson = JSON.parse(appJsonFile.content);
        appJson.expo = {
          ...appJson.expo,
          slug: slug,
          extra: { eas: { projectId: "YOUR_EXPO_PROJECT_ID" } },
        };
        folder.file("app.json", JSON.stringify(appJson, null, 2));
      } catch { /* keep original */ }
    }

    // Add build README
    folder.file(
      "BUILD_GUIDE.md",
      `# Building ${project.name} with Expo EAS

Generated by [Kaafi](https://kaafi.app)

## Prerequisites
\`\`\`bash
npm install -g @expo/eas-cli
eas login          # sign in with your Expo account
\`\`\`

## Android APK (test builds, no Play Store)
\`\`\`bash
npm install
eas build --platform android --profile preview
\`\`\`
→ Download the APK from the link EAS gives you. Install directly on any Android device.

## Android AAB (Play Store production)
\`\`\`bash
eas build --platform android --profile production
\`\`\`

## iOS (TestFlight)
Requires Apple Developer account ($99/year).
\`\`\`bash
eas build --platform ios --profile production
eas submit --platform ios          # submits to TestFlight
\`\`\`

## First-time setup
EAS will ask to generate a keystore on first build. Say **yes** — it handles everything.

## Troubleshooting
- Run \`eas build:configure\` if you get config errors
- Set your Expo project ID in \`app.json\` under \`expo.extra.eas.projectId\`
`
    );

    const buffer = await zip.generateAsync({ type: "uint8array", compression: "DEFLATE" });

    // Mark build as "building" (in real impl, this would poll EAS API)
    if (build) {
      await supabase
        .from("builds")
        .update({ status: "building", updated_at: new Date().toISOString() })
        .eq("id", build.id);
    }

    return new NextResponse(buffer as unknown as BodyInit, {
      headers: {
        "Content-Type": "application/zip",
        "Content-Disposition": `attachment; filename="${slug}-eas-ready.zip"`,
        "X-Build-Id": build?.id ?? "",
      },
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : "Build failed.";
    console.error("[/api/build]", msg);
    return NextResponse.json({ error: msg }, { status: 500 });
  }
}
